import "server-only";
import { createHash } from "node:crypto";
import { S3Client, PutObjectCommand, GetObjectCommand, HeadObjectCommand } from "@aws-sdk/client-s3";
import { required, type InfraEnv } from "@vynvori/shared/infrastructure";
import { r2Target } from "./storage";

const keyPattern = /^private\/composition\/v1\/[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\/[a-f0-9]{64}$/;
type Sender = Pick<S3Client, "send">;
export interface CompositionAssetStorage {
  put(key: string, bytes: Uint8Array, mime: string, sha256: string): Promise<void>;
  get(key: string, expectedSha256: string, expectedBytes: number): Promise<Uint8Array>;
}
const status = (error: unknown) => (error as { $metadata?: { httpStatusCode?: number } }).$metadata?.httpStatusCode;

/**
 * Private, content-addressed, write-once customer originals. Reuses the M2 R2 target resolution (`r2Target`: pinned account,
 * `vynvori-staging-*` bucket, jurisdiction endpoint). The M2 synthetic adapter itself only accepts one approved PNG and is
 * left byte-for-byte unchanged. Keys are generated by the server from validated IDs + the content hash, never from client input;
 * there is no delete and no overwrite (`If-None-Match: *`), and no URL is ever issued to a client.
 */
export function compositionAssetStorage(env: InfraEnv, sender?: Sender): CompositionAssetStorage & { close(): void } {
  const { bucket, endpoint } = r2Target(env);
  const client = sender ?? new S3Client({
    endpoint, region: "auto", maxAttempts: 1, requestChecksumCalculation: "WHEN_REQUIRED", responseChecksumValidation: "WHEN_REQUIRED",
    credentials: { accessKeyId: required(env, "M2_R2_ACCESS_KEY_ID"), secretAccessKey: required(env, "M2_R2_SECRET_ACCESS_KEY") },
  });
  const digest = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");
  return {
    async put(key, bytes, mime, sha256) {
      if (!keyPattern.test(key) || !key.endsWith("/" + sha256) || digest(bytes) !== sha256 || !["image/png", "image/jpeg", "image/webp"].includes(mime)) throw new Error("Invalid asset write");
      try {
        await client.send(new PutObjectCommand({ Bucket: bucket, Key: key, Body: bytes, ContentLength: bytes.byteLength, ContentType: mime, IfNoneMatch: "*", Metadata: { sha256, kind: "customer_original" } }), { abortSignal: AbortSignal.timeout(20000) });
      } catch (error) {
        if (status(error) !== 412) throw error;
        // Already present (idempotent retry after a lost acknowledgement). Accept ONLY if it is verifiably the same bytes.
        const head = await client.send(new HeadObjectCommand({ Bucket: bucket, Key: key }), { abortSignal: AbortSignal.timeout(5000) });
        if (head.Metadata?.sha256 !== sha256 || head.ContentLength !== bytes.byteLength) throw new Error("Foreign object at content-addressed key; preserve it");
      }
    },
    async get(key, expectedSha256, expectedBytes) {
      if (!keyPattern.test(key) || !key.endsWith("/" + expectedSha256)) throw new Error("Invalid asset read");
      const controller = new AbortController(), timer = setTimeout(() => controller.abort(), 20000);
      try {
        const result = await client.send(new GetObjectCommand({ Bucket: bucket, Key: key }), { abortSignal: controller.signal });
        if (result.ContentLength !== expectedBytes || result.Metadata?.sha256 !== expectedSha256) throw new Error("Asset integrity failure");
        const chunks: Uint8Array[] = []; let total = 0;
        for await (const chunk of result.Body as unknown as AsyncIterable<Uint8Array>) {
          total += chunk.byteLength; if (total > expectedBytes) throw new Error("Asset exceeds recorded size"); chunks.push(chunk);
        }
        const bytes = Buffer.concat(chunks);
        if (bytes.byteLength !== expectedBytes || digest(bytes) !== expectedSha256) throw new Error("Asset integrity failure");
        return bytes;
      } finally { clearTimeout(timer); controller.abort(); }
    },
    close() { if (!sender) (client as S3Client).destroy(); },
  };
}

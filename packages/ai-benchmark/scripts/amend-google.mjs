import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const id = 'google/gemini-3.1-flash-image';
const source = `https://openrouter.ai/api/v1/images/models/${id}/endpoints`;
const response = await fetch(source, { signal: AbortSignal.timeout(15000) });
if (!response.ok) throw new Error(`Catalog HTTP ${response.status}`);
const catalog = await response.json();
const endpoint = catalog.endpoints.find(e => e.provider_tag === 'google-ai-studio');
if (!endpoint || !endpoint.supported_parameters.input_references || !endpoint.supported_parameters.resolution.values.includes('1K')) throw new Error('Incompatible replacement');
const snapshot = {accessedAt:new Date().toISOString(),url:source,data:catalog};
await writeFile(new URL('data/research/google__gemini-3.1-flash-image.json',root),JSON.stringify(snapshot,null,2));
const read = async name => JSON.parse(await readFile(new URL(name,root),'utf8'));
const write = async(name,value)=>writeFile(new URL(name,root),JSON.stringify(value,null,2)+'\n');
const models=await read('config/models.json');const config=await read('config/benchmark.json');const tasks=await read('config/concepts.json');
const old=models.find(m=>m.id==='google/gemini-nano-banana-2.1');
const replacement={...old,id,capabilities:endpoint.supported_parameters,pricingSource:source,pricingVersion:snapshot.accessedAt,pricing:endpoint.pricing};
if(!models.some(m=>m.id===id))models.push(replacement);
if(!config.authorizedModels.includes(id))config.authorizedModels.push(id);
const amended=tasks.map(t=>t.modelId===old.id?{...t,modelId:id,taskId:createHash('sha256').update(`${config.experimentVersion}|${t.caseId}|${id}|concept|1`).digest('hex').slice(0,24)}:t);
await write('config/models.json',models);await write('data/model-manifest.json',models);await write('config/benchmark.json',config);await write('config/concepts.json',amended);
await write('data/google-replacement-amendment.json',{date:snapshot.accessedAt,originalModel:old.id,replacement:id,reason:'Two confirmed zero-charge HTTP 429 rejections for Nano Banana 2.1. Explicit separate candidate, no runtime fallback.',scope:'Same briefs, references, 1K concept settings. Old requests remain in ledger.'});
console.log(JSON.stringify(catalog));
